// Banco: PostgreSQL (VM da Oracle em produção, Docker local em desenvolvimento e testes). Todas as consultas são assíncronas.
// O SQL do código usa `?` (ou `?N`) como no SQLite; `pg()` converte para `$N`.
import pg from 'pg';
import { createHash, randomBytes, scryptSync, timingSafeEqual } from 'node:crypto';

try { process.loadEnvFile(); } catch {} // .env é opcional se as variáveis já existirem
export const env = process.env;

pg.types.setTypeParser(20, Number);     // bigint (COUNT, ts) → number; ts em ms cabe com folga em 2^53
pg.types.setTypeParser(1700, parseFloat); // numeric (SUM de bigint) → number
const url = env.DATABASE_URL || 'postgres://rastro:rastro@127.0.0.1:55432/rastro';
const schema = env.DATABASE_SCHEMA; // só os testes usam: um schema por arquivo de teste
if (schema && !/^\w+$/.test(schema)) throw new Error('DATABASE_SCHEMA inválido');
const pool = new pg.Pool({ connectionString: url, max: Number(env.DATABASE_POOL) || 10, ...(schema && { options: `-c search_path=${schema}` }) });
const pgSql = sql => { let i = 0; return sql.replace(/\?(\d+)?/g, (_, n) => '$' + (n || ++i)); };
export const db = {
  all: async (sql, args = []) => (await pool.query(pgSql(sql), args)).rows,
  get: async (sql, args = []) => (await db.all(sql, args))[0],
  run: (sql, args = []) => pool.query(pgSql(sql), args),
  exec: sql => pool.query(sql), // vários comandos separados por ; e sem parâmetros
  /** Executa [[sql, args], …] numa transação. */
  async batch(stmts) {
    if (!stmts.length) return null;
    const c = await pool.connect();
    try {
      await c.query('BEGIN');
      for (const [sql, args = []] of stmts) await c.query(pgSql(sql), args);
      await c.query('COMMIT');
    } catch (e) { await c.query('ROLLBACK'); throw e; } finally { c.release(); }
  },
  end: () => pool.end(),
};

/** Resolve um objeto de promessas em paralelo: { a: p1, b: p2 } → { a: v1, b: v2 }. */
export const awaitAll = async o => Object.fromEntries(await Promise.all(Object.entries(o).map(async ([k, v]) => [k, await v])));

const T = "TEXT NOT NULL DEFAULT ''";
const ID = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';

export const sha = s => createHash('sha256').update(s).digest('hex');
export const newToken = () => randomBytes(24).toString('base64url');
export function hashPassword(p) {
  const salt = randomBytes(16);
  return salt.toString('hex') + ':' + scryptSync(p, salt, 32).toString('hex');
}
const DUMMY = hashPassword(randomBytes(8).toString('hex'));
export function checkPassword(p, stored) {
  const [s, h] = (stored || DUMMY).split(':'); // hash falso mantém o tempo constante para e-mails inexistentes
  return timingSafeEqual(scryptSync(String(p), Buffer.from(s, 'hex'), 32), Buffer.from(h, 'hex')) && !!stored;
}

/**
 * Cria o schema. Idempotente: roda a cada subida. Mudanças futuras são aditivas, no fim da lista,
 * com `ALTER TABLE … ADD COLUMN IF NOT EXISTS` (o Postgres faz isso nativamente).
 * Datas em ms ficam em BIGINT; valores em DOUBLE PRECISION.
 */
async function migrate() {
  if (schema) await db.exec(`CREATE SCHEMA IF NOT EXISTS ${schema}`);
  await db.exec(`
    -- Colunas de visita (referrer, channel, utm_*, country, screen, browser, os) são herdadas do primeiro
    -- evento da visita, então filtrar por elas filtra visitas inteiras.
    CREATE TABLE IF NOT EXISTS events(id ${ID}, site TEXT NOT NULL, date TEXT NOT NULL, ts BIGINT NOT NULL, visitor TEXT NOT NULL, session TEXT,
      name TEXT NOT NULL DEFAULT 'pageview', path TEXT NOT NULL DEFAULT '/', referrer ${T}, channel TEXT NOT NULL DEFAULT 'Direto',
      utm_source ${T}, utm_medium ${T}, utm_campaign ${T}, utm_term ${T}, utm_content ${T},
      screen TEXT NOT NULL DEFAULT '??', browser ${T}, os ${T}, country TEXT NOT NULL DEFAULT '??', props TEXT, revenue DOUBLE PRECISION);
    CREATE INDEX IF NOT EXISTS events_site_date ON events(site, date);
    CREATE INDEX IF NOT EXISTS events_visitor_ts ON events(visitor, ts);
    CREATE TABLE IF NOT EXISTS sites(id TEXT PRIMARY KEY, name TEXT NOT NULL, timezone TEXT NOT NULL DEFAULT 'UTC', currency TEXT NOT NULL DEFAULT 'BRL',
      share_token TEXT UNIQUE, created BIGINT, webhook_token TEXT UNIQUE, tax_rate DOUBLE PRECISION NOT NULL DEFAULT 0, meta_pixel TEXT, meta_capi_token TEXT);
    CREATE TABLE IF NOT EXISTS salts(date TEXT PRIMARY KEY, salt TEXT NOT NULL);

    CREATE TABLE IF NOT EXISTS users(id ${ID}, email TEXT NOT NULL, name ${T},
      role TEXT NOT NULL CHECK(role IN ('admin','editor','viewer')), pass TEXT, invite TEXT UNIQUE, invite_expires BIGINT, created BIGINT);
    CREATE UNIQUE INDEX IF NOT EXISTS users_email ON users(lower(email));
    CREATE TABLE IF NOT EXISTS user_sites(user_id BIGINT NOT NULL, site_id TEXT NOT NULL, PRIMARY KEY(user_id, site_id));
    CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, user_id BIGINT NOT NULL, expires BIGINT NOT NULL);
    CREATE TABLE IF NOT EXISTS login_fails(ip TEXT PRIMARY KEY, n INTEGER NOT NULL, until BIGINT NOT NULL);
    CREATE TABLE IF NOT EXISTS funnels(id ${ID}, site_id TEXT NOT NULL, name TEXT NOT NULL, steps TEXT NOT NULL);

    -- Vendas (webhooks). Sem dados pessoais do comprador: e-mail/telefone só passam em memória (hash) para a Conversions API.
    CREATE TABLE IF NOT EXISTS sales(id ${ID}, site TEXT NOT NULL, platform TEXT NOT NULL, order_id TEXT NOT NULL,
      status TEXT NOT NULL CHECK(status IN ('paid','pending','refused','refunded','chargeback')), method TEXT NOT NULL DEFAULT 'other',
      gross DOUBLE PRECISION NOT NULL DEFAULT 0, net DOUBLE PRECISION NOT NULL DEFAULT 0, currency TEXT NOT NULL DEFAULT 'BRL', product ${T},
      ts BIGINT NOT NULL, date TEXT NOT NULL, updated BIGINT NOT NULL,
      utm_source ${T}, utm_medium ${T}, utm_campaign ${T}, utm_content ${T}, utm_term ${T},
      campaign_key ${T}, adset_key ${T}, ad_key ${T}, UNIQUE(site, platform, order_id));
    CREATE INDEX IF NOT EXISTS sales_site_date ON sales(site, date);
    CREATE TABLE IF NOT EXISTS webhook_log(id ${ID}, site TEXT NOT NULL, ts BIGINT NOT NULL,
      platform ${T}, order_id ${T}, status ${T}, ok INTEGER NOT NULL, message ${T});

    -- Anúncios (Meta)
    CREATE TABLE IF NOT EXISTS ad_accounts(id ${ID}, site TEXT NOT NULL, platform TEXT NOT NULL DEFAULT 'meta',
      account_id TEXT NOT NULL, name ${T}, currency ${T}, token TEXT NOT NULL, last_sync BIGINT, last_error TEXT, UNIQUE(site, platform, account_id));
    CREATE TABLE IF NOT EXISTS ad_entities(site TEXT NOT NULL, platform TEXT NOT NULL, level TEXT NOT NULL CHECK(level IN ('campaign','adset','ad')),
      id TEXT NOT NULL, name ${T}, parent ${T}, status ${T}, budget DOUBLE PRECISION, PRIMARY KEY(site, platform, level, id));
    -- meta_*: conversões reportadas pela própria Meta (para comparar com as vendas reais dos webhooks).
    CREATE TABLE IF NOT EXISTS ad_spend(site TEXT NOT NULL, platform TEXT NOT NULL, date TEXT NOT NULL,
      campaign_id TEXT NOT NULL, campaign_name ${T}, adset_id ${T}, adset_name ${T}, ad_id ${T}, ad_name ${T},
      spend DOUBLE PRECISION NOT NULL DEFAULT 0, impressions BIGINT NOT NULL DEFAULT 0, clicks BIGINT NOT NULL DEFAULT 0, source TEXT NOT NULL DEFAULT 'api',
      meta_purchases BIGINT NOT NULL DEFAULT 0, meta_purchase_value DOUBLE PRECISION NOT NULL DEFAULT 0, meta_leads BIGINT NOT NULL DEFAULT 0,
      PRIMARY KEY(site, platform, date, campaign_id, adset_id, ad_id));
    CREATE INDEX IF NOT EXISTS ad_spend_site_date ON ad_spend(site, date);
  `);
  for (const { id } of await db.all('SELECT id FROM sites WHERE webhook_token IS NULL')) await db.run('UPDATE sites SET webhook_token=? WHERE id=?', [newToken(), id]);

  if (!await db.get('SELECT 1 FROM users LIMIT 1')) {
    if (!env.ADMIN_EMAIL || !env.ADMIN_PASSWORD) throw new Error('Defina ADMIN_EMAIL e ADMIN_PASSWORD (veja .env.example) para criar o primeiro admin');
    await db.run("INSERT INTO users(email, name, role, pass, created) VALUES (?, 'Admin', 'admin', ?, ?)", [env.ADMIN_EMAIL, hashPassword(env.ADMIN_PASSWORD), Date.now()]);
  }
  await loadSites();
}

/**
 * Cache dos sites em memória (lido por beacons e webhooks). Em serverless cada instância tem o seu,
 * então ele é recarregado a cada 10 s e logo após qualquer alteração feita pela própria instância.
 */
export let sites = new Map();
let loadedAt = 0;
export async function loadSites() {
  sites = new Map((await db.all('SELECT * FROM sites ORDER BY lower(name)')).map(s => [s.id, s]));
  loadedAt = Date.now();
}
export const refreshSites = () => Date.now() - loadedAt > 10e3 ? loadSites() : undefined;

/** Aguarde antes de usar o banco: schema migrado e cache carregado. */
export const ready = migrate();
